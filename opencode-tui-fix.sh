install_crhandler() {
  _L="$PREFIX/lib/opencode/libopencode-crhandler.so"
  mkdir -p "$PREFIX/lib/opencode"
  if [ -f "$_L" ] && [ ! -f "${_L}.official-minimal" ]; then
    cp -p "$_L" "${_L}.official-minimal"
    say "backed up stock crhandler -> ${_L}.official-minimal"
  fi
  if command -v clang >/dev/null 2>&1; then
    _c="$(mktemp "${TMPDIR:-$PREFIX/tmp}/crhandler.XXXXXX.c")"
    crhandler_write_src "$_c"
    if clang -shared -fPIC -O2 -o "${_L}.new" "$_c" 2>/dev/null; then
      rm -f "$_c"; mv -f "${_L}.new" "$_L"; chmod 644 "$_L"
      say "crhandler v2 compiled from source -> $_L"
      return 0
    fi
    rm -f "$_c"
    say "crhandler compile failed — using embedded prebuilt"
  fi
  crhandler_write_bin "${_L}.new" || die "cannot write prebuilt crhandler"
  mv -f "${_L}.new" "$_L"; chmod 644 "$_L"
  say "crhandler v2 prebuilt installed -> $_L"
}

# ── 3. decide: wrap or self-retire ───────────────────────────────────────────
if [ "$MODE" = check ]; then
  if is_wrapper; then say "state: wrapper active at $BIN (opencode.real: $( [ -x "$REAL" ] && echo present || echo MISSING))"
  else say "state: plain binary at $BIN (no wrapper)"; fi
  say "check only — nothing changed. Run without arguments to apply."
  exit 0
fi

if is_wrapper; then
  [ -x "$REAL" ] || die "wrapper active but $REAL missing — run --unwrap after reinstalling the deb"
  # is upstream fixed now? smoke the real binary WITHOUT shim
  if smoke "$REAL"; then
    say "upstream binary now passes the TUI smoke test — self-retiring"
    mv -f "$REAL" "$BIN"
    rm -f "$LIB"
    say "stock binary restored, wrapper and shim removed. Done."
    exit 0
  fi
  install_shim
  say "smoke-testing wrapped binary (25 s max)..."
  if smoke "$BIN" "$LIB"; then
    say "OK: TUI alive under the shim. opencode $installed_ver ready."
  elif [ "$(grep -ac 'Pointer exceeds safe integer range' "$LOG")" != "0" ]; then
    die "still crashing under the shim — unexpected; keep install1.md notes handy"
  else
    die "smoke inconclusive (no crash line, but TUI did not stay alive) — inspect $LOG"
  fi
  exit 0
fi

# plain stock binary at $BIN
if [ "$MODE" = force ]; then
  install_shim
  mv -f "$BIN" "$REAL"
  write_wrapper
  say "forced wrap done (--force). Verify by running: opencode"
  exit 0
fi

say "smoke-testing stock binary WITHOUT shim (25 s max)..."
if smoke "$BIN"; then
  say "stock binary passes — upstream fix present, no shim needed."
  if [ -x "$REAL" ] && ! is_wrapper; then rm -f "$REAL"; say "removed stale $REAL"; fi
  if [ -f "$LIB" ] && is_elf "$BIN"; then rm -f "$LIB"; say "removed stale $LIB"; fi
  say "Done. opencode $installed_ver ready."
elif grep -aq "Pointer exceeds safe integer range" "$LOG" 2>/dev/null; then
  say "confirmed: tagged-pointer TUI crash — applying shim + wrapper"
  install_shim
  mv -f "$BIN" "$REAL"
  write_wrapper
  say "smoke-testing wrapped binary (25 s max)..."
  if smoke "$BIN" "$LIB"; then
    say "OK: TUI alive under the shim. opencode $installed_ver ready."
    say "(the 25 s smoke run left the TUI in foreground; it exited with the test)"
  else
    die "wrapped binary still failing — inspect $LOG"
  fi
else
  # Non-pointer failure: the Android-10 / kernel-4.4 syscall trap gap is the
  # other known blocker on this exact install path (issue #37). Detect its
  # signature, swap in the emulating crhandler, re-test.
  if grep -aqE "ETIMEDOUT: .*stat|pidfd_open|Failed to start server|Unknown Error" "$LOG" 2>/dev/null; then
    say "trap-gap signature detected (statx/pidfd_open) — installing emulating crhandler v2"
    install_crhandler
    say "smoke-testing again with crhandler v2 (25 s max)..."
    if smoke "$BIN"; then
      say "OK: TUI alive with the emulating crhandler. opencode $installed_ver ready."
      say "(stock shim backup: $PREFIX/lib/opencode/libopencode-crhandler.so.official-minimal)"
    else
      die "still failing after the crhandler upgrade — inspect $LOG"
    fi
  else
    die "smoke inconclusive (no pointer error, no known trap signature) — inspect $LOG; use --force to wrap anyway"
  fi
fi
