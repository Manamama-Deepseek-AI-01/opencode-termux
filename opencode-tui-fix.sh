#!/bin/sh
# opencode-tui-fix — install/repair OpenCode (Termux, aarch64) so the TUI works
# on Android 11+ heap pointer tagging.
#
# Root cause (verified independently on Android 11/12/16 — upstream issues #43/#46):
# Android 11+ bionic scudo tags every heap pointer in the top byte (0xb4...);
# opentui 0.6.8+/0.8.0 returns such a pointer from ot_context_create and converts
# it to a JS number; anything > 2^53 trips opentui's own guard ("Pointer exceeds
# safe integer range") and the TUI dies. mallopt(M_BIONIC_SET_HEAP_TAGGING_LEVEL)
# needs API 31+, and scudo validates tags in free/realloc, so pointers cannot be
# simply untagged — the shim interposes the allocator boundary instead.
#
# What this script does (idempotent, self-retiring):
#   1. ensures the official opencode .deb is installed (fetches newest release
#      asset via the GitHub API, verifies sha256, dpkg -i; clears dpkg phantom
#      records like "installed but binary missing")
#   2. installs $PREFIX/lib/opencode/libnoheap.so — compiled on-device from the
#      embedded source when clang is available, else from the embedded prebuilt
#   3. smoke-tests the real binary WITHOUT any shim: if upstream's own fix has
#      landed (expected: a "-2" package revision per issue #43), nothing is
#      wrapped and any stale wrapper/shim is cleaned up
#      if the binary crashes with "Pointer exceeds safe integer range", it is
#      renamed to opencode.real and a tiny LD_PRELOAD wrapper is installed
#   4. verifies the result (TUI kept alive 25 s, no crash line)
#
# Usage:
#   opencode-tui-fix.sh              install/repair/upgrade (default)
#   opencode-tui-fix.sh --check      show what would be done, change nothing
#   opencode-tui-fix.sh --unwrap     restore stock binary, remove wrapper+shim
#   opencode-tui-fix.sh --force      skip smoke test, always wrap
#
# Sources: local analysis 2026-11-03 (install1.md in opencode-termux workspace);
# shim derived from jcz2020/opencode-termux src/noheap.c (mallopt path).
# NOTE for upgrades: apt/dpkg replaces bin/opencode with the new plain binary;
# just re-run this script afterwards. Never run "opencode upgrade".

set -eu

OWNER_REPO="Hope2333/opencode-termux"
WRAPPER_MARKER="opencode-tui-fix wrapper"
LOG="${TMPDIR:-/data/data/com.termux/files/usr/tmp}/opencode-tui-fix-smoke.log"

say() { printf '%s\n' "$*"; }
die() { printf 'opencode-tui-fix: %s\n' "$*" >&2; exit 1; }

case "${1-}" in
  "")      MODE=apply ;;
  --check) MODE=check ;;
  --unwrap) MODE=unwrap ;;
  --force) MODE=force ;;
  *) die "unknown argument: $1 (use --check | --unwrap | --force)" ;;
esac

# ── 0. Termux/aarch64 detection ──────────────────────────────────────────────
if [ -n "${PREFIX:-}" ] && [ -d "$PREFIX" ]; then :
elif [ -d /data/data/com.termux/files/usr ]; then
  PREFIX=/data/data/com.termux/files/usr
else
  die "only Termux (aarch64) is supported"
fi
[ "$(uname -m)" = "aarch64" ] || die "aarch64 only (found $(uname -m))"
SDK="$(getprop ro.build.version.sdk 2>/dev/null || echo '?')"
say "Termux prefix: $PREFIX   Android SDK: $SDK"

BIN="$PREFIX/bin/opencode"
REAL="$PREFIX/bin/opencode.real"
LIB="$PREFIX/lib/opencode/libnoheap.so"

# A launcher is any bash script at $BIN that execs opencode.real (covers the
# canonical wrapper below and hand-rolled variants). A stock binary is an ELF
# and never matches.
is_wrapper() {
  [ -f "$BIN" ] && [ -x "$BIN" ] || return 1
  head -c 512 "$BIN" 2>/dev/null | grep -q '^#!' || return 1
  head -c 4096 "$BIN" 2>/dev/null | grep -aq "opencode.real"
}
is_elf() { [ "$(head -c 4 "$1" 2>/dev/null | od -An -tx1 | tr -d ' \n')" = "7f454c46" ]; }

# smoke <binary> [LD_PRELOAD_VALUE] — returns 0 alive, 1 pointer crash, 2 other
smoke() {
  _bin="${1-}"; _pl="${2-}"
  [ -x "$_bin" ] || return 2
  ( cd "$HOME" 2>/dev/null || cd /
    if [ -n "$_pl" ]; then
      LD_PRELOAD="$_pl" TERM="${TERM:-xterm-256color}" timeout 25 \
        script -qec "$_bin" /dev/null >"$LOG" 2>&1
    else
      TERM="${TERM:-xterm-256color}" timeout 25 \
        script -qec "$_bin" /dev/null >"$LOG" 2>&1
    fi )
  rc=$?
  if grep -aq "Pointer exceeds safe integer range" "$LOG" 2>/dev/null; then return 1; fi
  [ "$rc" = 124 ] && return 0
  return 2
}

# ── 1. package: install / upgrade / repair the official .deb ─────────────────
installed_ver="$(dpkg-query -W -f='${Version}' opencode 2>/dev/null || true)"
say "dpkg opencode: ${installed_ver:-<not installed>}"

if [ "$MODE" = apply ] || [ "$MODE" = force ]; then
  json=""
  if ! json="$(curl -fsSL --max-time 25 "https://api.github.com/repos/$OWNER_REPO/releases/latest")"; then
    json=""
    say "WARNING: GitHub API unreachable (offline / flaky DNS) — package check skipped"
  fi
  if [ -z "$json" ] && [ -z "$installed_ver" ]; then
    die "no network and no opencode installed — install the deb manually first, then re-run"
  fi
  url="$(printf '%s\n' "$json" | grep -o '"browser_download_url": *"[^"]*opencode_[0-9][^"]*_aarch64\.deb"' \
        | sed 's/.*"\(https[^"]*\)".*/\1/' | tail -1)"
  if [ -z "$json" ]; then
    say "offline: using installed opencode ${installed_ver}"
  elif [ -z "$url" ]; then
    die "no opencode_*_aarch64.deb asset in latest release"
  fi
  latest_ver="$(printf '%s' "$url" | sed 's|.*/opencode_\([0-9A-Za-z.+~-]*\)_aarch64\.deb|\1|')"
  # GitHub lists "digest" BEFORE "browser_download_url" inside each asset
  # object — pair them by "last seen digest, then matching URL".
  digest="$(printf '%s\n' "$json" | awk -v u="$url" '
    $0 ~ /"digest": *"sha256:/ { match($0, /sha256:[a-f0-9]+/); last_digest = substr($0, RSTART+7, RLENGTH-7) }
    $0 ~ "browser_download_url" && index($0, u) != 0 { print last_digest }' | tail -1)"
  say "latest release asset: $(basename "$url") (dpkg: ${installed_ver:-none})"

  need_install=0
  if [ -z "$installed_ver" ]; then need_install=1; fi
  if [ -n "$latest_ver" ] && [ "$installed_ver" != "$latest_ver" ]; then need_install=1; fi
  if [ -z "$installed_ver" ] && [ ! -x "$BIN" ] && [ ! -x "$REAL" ]; then need_install=1; fi
  # phantom record: dpkg says installed but neither binary nor wrapper exists
  if [ -n "$installed_ver" ] && [ ! -x "$BIN" ] && [ ! -x "$REAL" ]; then
    say "phantom dpkg record (no binary on disk) — purging first"
    dpkg -P --force-all opencode >/dev/null 2>&1 || true
    installed_ver=""
    need_install=1
  fi

  if [ "$need_install" = 1 ]; then
    tmp="$(mktemp -d "${TMPDIR:-$PREFIX/tmp}/otf.XXXXXX")"
    trap 'rm -rf "$tmp" 2>/dev/null' EXIT INT TERM
    say "downloading $(basename "$url")"
    curl -fL --retry 3 --retry-delay 2 -o "$tmp/opencode.deb" "$url" \
      || die "download failed: $url"
    if [ -n "$digest" ]; then
      got="$(sha256sum "$tmp/opencode.deb" | awk '{print $1}')"
      [ "$got" = "$digest" ] || die "sha256 mismatch ($got != $digest)"
      say "sha256 ok"
    else
      say "WARNING: digest not found in API response — skipping verification"
    fi
    dpkg -i "$tmp/opencode.deb" || die "dpkg -i failed"
    rm -rf "$tmp"
    installed_ver="$(dpkg-query -W -f='${Version}' opencode)"
    say "installed opencode $installed_ver"
  else
    say "package up to date ($installed_ver) — skipping download"
  fi
fi

# ── 2. shim: compile from source when possible, else embedded prebuilt ───────
if [ "$MODE" = unwrap ]; then
  if is_wrapper && [ -x "$REAL" ]; then
    mv -f "$REAL" "$BIN" && say "restored stock binary at $BIN"
  fi
  rm -f "$LIB"
  say "shim removed. TUI fix fully reverted."
  exit 0
fi

install_shim() {
  mkdir -p "$PREFIX/lib/opencode"
  if command -v clang >/dev/null 2>&1; then
    csrc="$(mktemp "${TMPDIR:-$PREFIX/tmp}/noheap.XXXXXX.c")"
    cat > "$csrc" <<'NOHEAP_C_SRC'
/*
 * libnoheap.so (v2) — make heap pointers JS-safe on bionic.
 *
 * Problem: Android 11+ bionic (scudo) tags every heap pointer in the top
 * byte (0xb4...). opentui 0.8 returns such a pointer from ot_context_create
 * and converts it to a JS number in bun:ffi; anything > 2^53 throws
 * "Pointer exceeds safe integer range" and the TUI dies.
 *
 * The clean fix, mallopt(M_BIONIC_SET_HEAP_TAGGING_LEVEL, NONE), exists only
 * since API 31 (Android 12). On Android 11 (API 30) it returns 0 and the tag
 * stays. The allocator also *validates* tags in free/realloc ("Pointer tag
 * ... was truncated"), so pointers cannot simply be untagged.
 *
 * This shim interposes the allocator boundary instead:
 *   - allocations returned to the app are stripped of the tag byte
 *   - pointers passed back to the real allocator (free/realloc/usable_size)
 *     get the tag byte restored, sampled live at startup
 * On Android 12+, mallopt(NONE) succeeds, the sampled tag is 0 and every
 * wrapper degrades to a plain passthrough.
 *
 * Derived from jcz2020/opencode-termux src/noheap.c (mallopt path).
 * Build: clang -shared -fPIC -O2 -o libnoheap.so noheap.c
 * Debug: NOHEAP_DEBUG=1
 */
#define _GNU_SOURCE
#include <dlfcn.h>
#include <malloc.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

extern int mallopt(int __option, int __value);

#define TAG_MASK 0x00FFFFFFFFFFFFFFULL
/* provisional until the constructor samples the live tag; refined there */
static uintptr_t tag_top = 0xB4ULL << 56;
static int sampled = 0;

static void* (*real_malloc)(size_t);
static void* (*real_calloc)(size_t, size_t);
static void* (*real_realloc)(void*, size_t);
static void* (*real_reallocarray)(void*, size_t, size_t);
static void* (*real_memalign)(size_t, size_t);
static void* (*real_aligned_alloc)(size_t, size_t);
static void* (*real_valloc)(size_t);
static void* (*real_pvalloc)(size_t);
static int (*real_posix_memalign)(void**, size_t, size_t);
static void (*real_free)(void*);
static size_t (*real_malloc_usable_size)(void*);

static volatile int resolving = 0;

/* Pre-resolution fallback arena: only live between process start and the
 * constructor (e.g. allocations inside dlsym itself). Tiny by design. */
static unsigned char arena[1 << 16] __attribute__((aligned(16)));
static volatile size_t arena_off;

static int in_arena(const void* p) {
  return (const unsigned char*)p >= arena && (const unsigned char*)p < arena + sizeof(arena);
}

static void* arena_malloc(size_t n) {
  size_t need = (n + 15) & ~(size_t)15;
  size_t off = __atomic_fetch_add(&arena_off, need + 16, __ATOMIC_RELAXED);
  if (off + need + 16 > sizeof(arena)) return NULL;
  unsigned char* chunk = arena + off;
  *(size_t*)chunk = n;
  return chunk + 16;
}

static size_t arena_usable(void* p) {
  if (!in_arena(p)) return 0;
  return *(size_t*)((unsigned char*)p - 16);
}

static void ensure_resolved(void) {
  if (real_malloc || resolving) return;
  resolving = 1;
  real_malloc = dlsym(RTLD_NEXT, "malloc");
  real_calloc = dlsym(RTLD_NEXT, "calloc");
  real_realloc = dlsym(RTLD_NEXT, "realloc");
  real_reallocarray = dlsym(RTLD_NEXT, "reallocarray");
  real_memalign = dlsym(RTLD_NEXT, "memalign");
  real_aligned_alloc = dlsym(RTLD_NEXT, "aligned_alloc");
  real_valloc = dlsym(RTLD_NEXT, "valloc");
  real_pvalloc = dlsym(RTLD_NEXT, "pvalloc");
  real_posix_memalign = dlsym(RTLD_NEXT, "posix_memalign");
  real_free = dlsym(RTLD_NEXT, "free");
  real_malloc_usable_size = dlsym(RTLD_NEXT, "malloc_usable_size");
  resolving = 0;
}

static void* strip(void* p) { return p ? (void*)((uintptr_t)p & TAG_MASK) : p; }

/* Restore the allocator's tag byte. Pointers that already carry a nonzero
 * top byte (e.g. from non-interposed libc-internal allocations) pass
 * through untouched. */
static void* retag(void* p) {
  uintptr_t u = (uintptr_t)p;
  if (!p || (u >> 56) || !tag_top) return p;
  return (void*)(u | tag_top);
}

__attribute__((constructor))
static void noheap_init(void) {
  ensure_resolved();
  if (!real_malloc) return;

  /* Try the supported API first (Android 12+): if it works the allocator is
   * untagged and every wrapper below becomes a passthrough. */
  int mallopt_rc = mallopt(M_BIONIC_SET_HEAP_TAGGING_LEVEL, M_HEAP_TAGGING_LEVEL_NONE);

  /* Sample the tag the allocator actually produces right now. */
  void* probe = real_malloc(32);
  if (probe) {
    tag_top = ((uintptr_t)probe >> 56) << 56;
    real_free(probe);
    sampled = 1;
  }

  if (getenv("NOHEAP_DEBUG")) {
    fprintf(stderr,
            "NOHEAP: mallopt=%d sampled_tag=0x%02x mode=%s\n",
            mallopt_rc,
            (unsigned)(tag_top >> 56),
            tag_top ? "interpose (strip/restore)" : "passthrough (untagged heap)");
  }
}

void* malloc(size_t n) {
  ensure_resolved();
  if (!real_malloc) return arena_malloc(n);
  return strip(real_malloc(n));
}

void* calloc(size_t n, size_t s) {
  ensure_resolved();
  if (!real_calloc) {
    void* p = arena_malloc(n * s);
    if (p) memset(p, 0, n * s);
    return p;
  }
  return strip(real_calloc(n, s));
}

void* realloc(void* p, size_t n) {
  ensure_resolved();
  if (!p) return malloc(n);
  if (in_arena(p)) {
    size_t old = arena_usable(p);
    void* np = malloc(n);
    if (np) memcpy(np, p, old < n ? old : n);
    return np;
  }
  if (!real_realloc) return NULL;
  return strip(real_realloc(retag(p), n));
}

void* reallocarray(void* p, size_t n, size_t s) {
  ensure_resolved();
  size_t total;
  if (__builtin_mul_overflow(n, s, &total)) return NULL;
  if (real_reallocarray) return strip(real_reallocarray(retag(p), n, s));
  return realloc(p, total);
}

void* memalign(size_t align, size_t n) {
  ensure_resolved();
  if (!real_memalign) return NULL;
  return strip(real_memalign(align, n));
}

void* aligned_alloc(size_t align, size_t n) {
  ensure_resolved();
  if (real_aligned_alloc) return strip(real_aligned_alloc(align, n));
  if (real_memalign) return strip(real_memalign(align, n));
  return NULL;
}

void* valloc(size_t n) {
  ensure_resolved();
  if (real_valloc) return strip(real_valloc(n));
  if (real_memalign) return strip(real_memalign((size_t)sysconf(_SC_PAGESIZE), n));
  return NULL;
}

void* pvalloc(size_t n) {
  ensure_resolved();
  size_t page = (size_t)sysconf(_SC_PAGESIZE);
  size_t rounded = (n + page - 1) & ~(page - 1);
  if (real_pvalloc) return strip(real_pvalloc(n));
  return memalign(page, rounded ? rounded : page);
}

int posix_memalign(void** out, size_t align, size_t n) {
  ensure_resolved();
  if (!real_posix_memalign) return 1;
  int rc = real_posix_memalign(out, align, n);
  if (rc == 0 && out) *out = strip(*out);
  return rc;
}

void free(void* p) {
  if (!p) return;
  if (in_arena(p)) return; /* arena chunks are never reclaimed */
  ensure_resolved();
  if (!real_free) return;
  real_free(retag(p));
}

size_t malloc_usable_size(const void* p) {
  if (!p) return 0;
  if (in_arena(p)) return arena_usable((void*)p);
  ensure_resolved();
  if (!real_malloc_usable_size) return 0;
  return real_malloc_usable_size(retag((void*)p));
}
